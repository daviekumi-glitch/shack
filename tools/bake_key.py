#!/usr/bin/env python3
"""Write shack/builtin_key.py from SHACK_BUILTIN_KEY before a build.

Usage:
    SHACK_BUILTIN_KEY=gsk_... python3 tools/bake_key.py

The file is gitignored. Running it with an empty variable resets the module, so
builds can go back to asking for a key.
"""

from __future__ import annotations

import os
from pathlib import Path

TARGET = Path(__file__).resolve().parent.parent / "shack" / "builtin_key.py"

TEMPLATE = '''"""A key baked into the build, so a fresh install never asks for one.

Generated by tools/bake_key.py. Not in git on purpose.
"""

from __future__ import annotations

_KEY = {key!r}


def get() -> str:
    return _KEY
'''


def main() -> int:
    key = (os.environ.get("SHACK_BUILTIN_KEY") or "").strip()
    TARGET.write_text(TEMPLATE.format(key=key))
    if key:
        print(f"baked a key of {len(key)} characters into {TARGET}")
    else:
        print("no SHACK_BUILTIN_KEY set, the app will ask for a key")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
